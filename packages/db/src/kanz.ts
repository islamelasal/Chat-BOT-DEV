/** تطبيع النص العربي — إزالة التشكيل + توحيد الهمزات والألف/الياء/التاء المربوطة (يُستخدم في المطابقة والبحث) */
export function normalizeArabic(text: string): string {
  return text
    .replace(/[\u064B-\u0652\u0670\u0640]/g, '')   // تشكيل وتطويل
    .replace(/[أإآا]/g, 'ا')                        // همزات وألفات
    .replace(/ى/g, 'ي')                             // ياء مقصورة
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/ة/g, 'ه')                             // تاء مربوطة
    .replace(/ڤ/g, 'ف')
    .replace(/پ/g, 'ب')
    .replace(/چ/g, 'ج')
    .toLowerCase()
    .trim();
}
