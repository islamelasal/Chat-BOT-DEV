function currentDate() {
  try {
    return new Intl.DateTimeFormat('ar-EG', {
      year: 'numeric',
      month: 'long',
      day: 'numeric'
    }).format(new Date());
  } catch {
    return new Date().toISOString().slice(0, 10);
  }
}

